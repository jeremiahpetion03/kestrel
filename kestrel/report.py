"""Turn a run's measured outputs into RESULTS.md. Every number in the report
is read from files the run produced; nothing is typed in by hand.

    python -m kestrel.report --run runs/shakespeare
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def render(run: Path) -> str:
    cfg, final, bench = _load(run / "config.json"), _load(run / "final.json"), _load(run / "bench.json")
    t, m = cfg["train"], cfg["model"]
    lines = [
        "# Kestrel results",
        "",
        f"Generated by `python -m kestrel.report --run {run.as_posix()}` from `config.json`, "
        "`final.json`, and `bench.json`.",
        "",
        f"Hardware: CPU, {cfg['threads']} threads. PyTorch {cfg['torch']}, Python {cfg['python']}.",
        "",
        "## Training",
        "",
        "| | |",
        "|---|---|",
        f"| Model | {final['num_params']:,} parameters ({m['n_layer']} layers, {m['n_head']} heads, "
        f"d={m['d_model']}, context {m['block_size']}) |",
        f"| Data | TinyShakespeare, character-level, vocab {m['vocab_size']}; "
        f"{cfg['train_tokens']:,} train / {cfg['val_tokens']:,} held-out tokens |",
        f"| Schedule | {t['steps']:,} steps x batch {t['batch']}, AdamW, warmup + cosine, "
        f"precision {t['precision']} |",
        f"| **Validation loss** | **{final['val_loss']}** (perplexity {final['val_perplexity']}) |",
        f"| Train time | {final['train_seconds']} s ({final['train_tokens_per_sec']:,} tokens/s) |",
        "",
        "## Training step: precision x gradient checkpointing",
        "",
        "| Precision | Checkpointing | Step (ms) | Tokens/s | Activation memory (MB) |",
        "|---|---|---|---|---|",
    ]
    base = next(r for r in bench["training"] if r["precision"] == "fp32" and not r["grad_checkpoint"])
    for r in bench["training"]:
        lines.append(
            f"| {r['precision']} | {'on' if r['grad_checkpoint'] else 'off'} | {r['median_step_ms']} "
            f"| {r['tokens_per_sec']:,} | {r['saved_activation_mb']} "
            f"({r['saved_activation_mb'] / base['saved_activation_mb']:.2f}x) |"
        )
    gen, q = bench["generation"], bench["quantization"]
    lines += [
        "",
        "## Generation: KV cache",
        "",
        f"{gen['new_tokens']} new tokens, greedy. Output verified **token-for-token identical** "
        "with and without the cache.",
        "",
        "| | Time (ms) | Tokens/s |",
        "|---|---|---|",
        f"| Recompute full prefix each step | {gen['uncached']['median_ms']} | {gen['uncached']['tokens_per_sec']:,} |",
        f"| KV cache | {gen['cached']['median_ms']} | {gen['cached']['tokens_per_sec']:,} |",
        f"| **Speedup** | **{gen['speedup']}x** | |",
        "",
        "## Int8 weight-only quantization",
        "",
        "| | fp32 | int8 |",
        "|---|---|---|",
        f"| Model size (MB) | {q['fp32_mb']} | {q['int8_mb']} ({q['size_reduction']}x smaller) |",
        f"| Validation loss | {q['val_loss_fp32']} | {q['val_loss_int8']} ({q['val_loss_delta']:+}) |",
        f"| Forward latency, batch 8 (ms) | {q['forward_ms_fp32']} | {q['forward_ms_int8']} |",
        "",
        f"Max absolute logit difference: {q['max_abs_logit_diff']}.",
    ]
    sample = run / "sample.txt"
    if sample.exists():
        text = sample.read_text(encoding="utf-8")[:400]
        lines += ["", "## Sample (temperature 0.8)", "", "```", text, "```"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--run", type=Path, default=Path("runs/shakespeare"))
    p.add_argument("--out", type=Path, default=Path("RESULTS.md"))
    args = p.parse_args(argv)
    args.out.write_text(render(args.run), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
